
SELECT
    ID_CMD,
    NO_LIGNE,
    DATE_CMD,
    UPPER(TRIM(STATUT_CMD)) AS STATUT_CMD,
    UPPER(TRIM(MODE_PAIEMENT)) AS MODE_PAIEMENT,

    ID_CLT,
    NOM,
    PRENOM,

    ID_VARIANTE,
    REFERENCE_SKU,
    TAILLE,
    COULEUR,

    ID_PDT,
    NOM_PDT,
    ID_FP,
    NOM_FP,

    QUANTITE,
    PRIX_UNITAIRE,
    COALESCE(REMISE, 0) AS REMISE,

    MONTANT_BRUT,
    MONTANT_NET,

    CASE
        WHEN UPPER(TRIM(STATUT_CMD)) = 'LIVREE'
        THEN MONTANT_NET
        ELSE 0
    END AS CA_REALISE,

    CASE
        WHEN UPPER(TRIM(STATUT_CMD)) = 'LIVREE'
        THEN QUANTITE
        ELSE 0
    END AS QUANTITE_LIVREE

FROM {{ ref('int_ventes') }}
